// ------------------------------------------------------------
// Main builder
// ------------------------------------------------------------

export function buildDoctorSummaryHTML(
  entries: PeriodEntry[],
  dayNotes: DayNotesMap,
  profile: Profile | null,
  bbtUnit: "C" | "F",
): string {
  const sorted = getSortedEntries(entries);
  const predictions = computePredictions(sorted);
  const regularity = getRegularityInsight(sorted);

  const generatedOn = new Date().toLocaleDateString(undefined, {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  // Last 6 months of cycles
  const cutoff = addDays(today(), -182);
  const recent = sorted.filter((e) => parseDate(e.startDate) >= cutoff);

  const cycleStats = computeCycleStats(recent);
  const bbtStats = computeBBTStats(dayNotes, bbtUnit);

  const cycleChartSVG = buildCycleChartSVG(recent, 620, 200);

  const tableRows = buildTableRows(recent);

  return `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>${styles()}</style>
</head>
<body>
  <h1>Cycle Summary</h1>
  <div class="meta">
    ${profile ? `<strong>${escape(profile.name)}</strong> · ` : ""}Generated ${generatedOn} · Last 6 months (${recent.length} ${recent.length === 1 ? "cycle" : "cycles"})
  </div>

  <div class="stat-row">
    <div class="stat">
      <div class="label">Average cycle</div>
      <div class="value">${predictions ? predictions.cycle + " days" : "—"}</div>
    </div>
    <div class="stat">
      <div class="label">Average period</div>
      <div class="value">${predictions ? predictions.periodLen + " days" : "—"}</div>
    </div>
    <div class="stat">
      <div class="label">Regularity</div>
      <div class="value">${regularity.label}</div>
    </div>
  </div>

  ${
    cycleChartSVG
      ? `
    <h2>Cycle length trend</h2>
    <div class="chart-block">
      ${cycleChartSVG}
      <div class="chart-caption">Cycle length (days) across recent cycles</div>
    </div>
  `
      : ""
  }

  ${
    predictions
      ? `
    <h2>Upcoming predictions</h2>
    <table class="pred-table">
      <tr><th>Next period</th><td>${formatDate(predictions.nextStart)} – ${formatDate(predictions.nextEnd)}</td></tr>
      <tr><th>Estimated ovulation</th><td>${formatDate(predictions.ovulation)}</td></tr>
      <tr><th>Fertile window</th><td>${formatDate(predictions.fertileStart)} – ${formatDate(predictions.fertileEnd)}</td></tr>
      <tr><th>Prediction confidence</th><td>${predictions.confidence.score}% (${predictions.confidence.label})</td></tr>
    </table>
  `
      : ""
  }

  <h2>Logged cycles</h2>
  <table>
    <thead>
      <tr>
        <th>Start</th>
        <th>End</th>
        <th>Period length</th>
        <th>Cycle length</th>
        <th>Symptoms</th>
        <th>Notes</th>
      </tr>
    </thead>
    <tbody>
      ${
        tableRows ||
        '<tr><td colspan="6" class="empty">No entries in this window.</td></tr>'
      }
    </tbody>
  </table>

  <h2>Basal body temperature</h2>
  <p>${
    bbtStats.count > 0
      ? `${bbtStats.count} readings · average ${bbtStats.avg.toFixed(2)} °${bbtUnit} · range ${bbtStats.min.toFixed(2)}–${bbtStats.max.toFixed(2)} °${bbtUnit}`
      : "No BBT data logged in this window."
  }</p>

  ${
    cycleStats.gapCount >= 2
      ? `
    <h2>Cycle statistics</h2>
    <table class="pred-table">
      <tr><th>Cycles analyzed</th><td>${cycleStats.gapCount}</td></tr>
      <tr><th>Shortest cycle</th><td>${cycleStats.min} days</td></tr>
      <tr><th>Longest cycle</th><td>${cycleStats.max} days</td></tr>
      <tr><th>Average cycle</th><td>${cycleStats.avg} days</td></tr>
      <tr><th>Standard deviation</th><td>${cycleStats.sd.toFixed(1)} days</td></tr>
    </table>
  `
      : ""
  }

  <p class="disclaimer">
    This summary was generated by a personal tracking app and is not a medical
    document. Predictions are estimates based on logged data. Please discuss
    any concerns with a healthcare provider.
  </p>
</body>
</html>`;
}

// ------------------------------------------------------------
// Stats helpers
// ------------------------------------------------------------

function computeCycleStats(sorted: PeriodEntry[]) {
  const gaps: number[] = [];
  for (let i = 1; i < sorted.length; i++) {
    const g = daysBetween(
      parseDate(sorted[i - 1].startDate),
      parseDate(sorted[i].startDate),
    );
    if (g > 15 && g < 60) gaps.push(g);
  }
  if (gaps.length === 0) {
    return { gapCount: 0, min: 0, max: 0, avg: 0, sd: 0 };
  }
  const avg = gaps.reduce((a, b) => a + b, 0) / gaps.length;
  const variance =
    gaps.reduce((acc, g) => acc + (g - avg) ** 2, 0) / gaps.length;
  return {
    gapCount: gaps.length,
    min: Math.min(...gaps),
    max: Math.max(...gaps),
    avg: Math.round(avg),
    sd: Math.sqrt(variance),
  };
}

function computeBBTStats(dayNotes: DayNotesMap, unit: "C" | "F") {
  const values: number[] = [];
  for (const rec of Object.values(dayNotes)) {
    if (rec && rec.bbt != null) {
      const display = unit === "C" ? rec.bbt : (rec.bbt * 9) / 5 + 32;
      values.push(display);
    }
  }
  if (values.length === 0) return { count: 0, avg: 0, min: 0, max: 0 };
  return {
    count: values.length,
    avg: values.reduce((a, b) => a + b, 0) / values.length,
    min: Math.min(...values),
    max: Math.max(...values),
  };
}

function buildTableRows(sorted: PeriodEntry[]): string {
  const recent = sorted.slice(-20).reverse(); // last 20 entries, newest first
  return recent
    .map((e, i) => {
      const start = formatDate(parseDate(e.startDate));
      const end = e.endDate ? formatDate(parseDate(e.endDate)) : "—";
      const len = e.endDate
        ? daysBetween(parseDate(e.startDate), parseDate(e.endDate)) + 1
        : "—";
      let cycle = "—";
      if (i < recent.length - 1) {
        const older = recent[i + 1];
        cycle = String(
          daysBetween(parseDate(older.startDate), parseDate(e.startDate)),
        );
      }
      const syms = (e.symptoms || []).join(", ") || "—";
      const notes = e.notes ? escape(e.notes) : "—";
      return `<tr>
        <td>${start}</td>
        <td>${end}</td>
        <td>${len}</td>
        <td>${cycle}</td>
        <td>${escape(syms)}</td>
        <td>${notes}</td>
      </tr>`;
    })
    .join("");
}

// ------------------------------------------------------------
// Inline SVG chart
// ------------------------------------------------------------

function buildCycleChartSVG(
  sorted: PeriodEntry[],
  width: number,
  height: number,
): string {
  const points: { value: number }[] = [];
  for (let i = 1; i < sorted.length; i++) {
    const gap = daysBetween(
      parseDate(sorted[i - 1].startDate),
      parseDate(sorted[i].startDate),
    );
    if (gap > 15 && gap < 60) points.push({ value: gap });
  }
  if (points.length === 0) return "";

  const pad = { top: 16, right: 16, bottom: 26, left: 36 };
  const W = width;
  const H = height;
  const chartW = W - pad.left - pad.right;
  const chartH = H - pad.top - pad.bottom;

  const values = points.map((p) => p.value);
  const minV = Math.min(...values) - 1;
  const maxV = Math.max(...values) + 1;

  const xStep = points.length > 1 ? chartW / (points.length - 1) : 0;
  const xOf = (i: number) => pad.left + i * xStep;
  const yOf = (v: number) =>
    pad.top + (1 - (v - minV) / (maxV - minV || 1)) * chartH;

  let grid = "";
  for (let g = 0; g <= 4; g++) {
    const v = minV + ((maxV - minV) * g) / 4;
    const y = yOf(v);
    grid += `<line x1="${pad.left}" y1="${y}" x2="${W - pad.right}" y2="${y}" stroke="#e0e0e0" stroke-width="1" />`;
    grid += `<text x="${pad.left - 6}" y="${y + 4}" font-size="10" fill="#777" text-anchor="end">${Math.round(v)}</text>`;
  }

  let path = "";
  let dots = "";
  points.forEach((p, i) => {
    const x = xOf(i);
    const y = yOf(p.value);
    path += i === 0 ? `M ${x} ${y}` : ` L ${x} ${y}`;
    dots += `<circle cx="${x}" cy="${y}" r="3.5" fill="#e88fb0" />`;
  });

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
    ${grid}
    <path d="${path}" fill="none" stroke="#e88fb0" stroke-width="2.4" stroke-linejoin="round" />
    ${dots}
  </svg>`;
}

// ------------------------------------------------------------
